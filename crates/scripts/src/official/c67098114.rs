use crate::prelude::*;
use crate::testing::{Check, EXTRA, GRAVE, HAND, MZONE, OPPONENT, SZONE};

const ID: u32 = 67098114;

struct Procedure;

impl SynchroProcedure for Procedure {
    const MIN2: usize = 2;
    const MAX2: usize = 99;

    fn f1(c: CardId, duel: &Duel, sc: CardId, sumtype: u64, tp: u8) -> bool {
        c.is_set_card_full(duel, &[SET_NORDIC_ALFAR], Some(sc), sumtype, tp) || c.is_has_effect(duel, EFFECT_SYNSUB_NORDIC).is_some()
    }

    fn f2(c: CardId, duel: &Duel, sc: CardId, _: u64, tp: u8) -> bool {
        Synchro::non_tuner(c, duel, sc, tp, aux::TRUE)
    }
}

// A copy on the field and in the Extra Deck, Synchro Summoned with Mara of the Nordic Alfar (a Level 2 Tuner) and two Noble Knight Artorigus (Level 4);
// Dark Hole in the opponent's hand destroys it, with Mara in the Graveyard to banish, Horn of Olifant (a Trap) to add, and Mirror Force and Dimensional Prison (Traps chained only to an attack) set on the opponent's side to negate.
