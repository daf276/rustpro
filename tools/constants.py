"""Regenerates crates/scripts/src/constant.rs from constant.lua and the two files it loads.

A name keeps the type it already has in constant.rs; a new name takes the most common type among the names that share
its longest underscore-separated prefix, or the type FAMILIES gives. Run from anywhere, then cargo fmt:
python tools/constants.py
"""
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, lua_constants

TARGET = ROOT / "crates/scripts/src/constant.rs"
# Families no existing name types: opcodes are u64 like Duel.AnnounceCard's stack, option strings u64 like HINTMSG,
# races u64 like RACE, card hints u8 like HINT, win reasons u8 like MSG_WIN's byte.
FAMILIES = {"OPCODE_": "u64", "DECLTYPE_": "u64", "SELECT_": "u64", "RACES_": "u64", "CHINT_": "u8", "PHINT_": "u8", "WIN_": "u8"}
RANGES = {"u8": (0, 2**8), "u16": (0, 2**16), "u32": (0, 2**32), "u64": (0, 2**64), "i32": (-2**31, 2**31)}


def infer(name, types):
    tokens = name.split("_")
    for count in range(len(tokens) - 1, 0, -1):
        prefix = "_".join(tokens[:count]) + "_"
        if prefix in FAMILIES:
            return FAMILIES[prefix]
        found = [kind for other, kind in types.items() if other.startswith(prefix)]
        if found:
            return collections.Counter(found).most_common(1)[0][0]
    return "u32"


def main():
    types = dict(re.findall(r"pub const (\w+): ([\w&\[\]]+) =", TARGET.read_text(encoding="utf-8")))
    constants = dict(lua_constants())
    values = {}
    lines = ["// Port of constant.lua with card_counter_constants.lua and archetype_setcode_constants.lua, generated by",
             "// tools/constants.py; types follow the API that takes each family.", ""]
    for name, expression in constants.items():
        # Rust constants are upper case; Lua has WIN_REASON_NUMBER_iC1000.
        rust_name = name.upper()
        if expression.startswith("{"):
            codes = expression.strip("{}").replace(",", ", ")
            lines.append(f"pub const {rust_name}: &[u32] = &[{codes}];")
            continue
        kind = types.get(rust_name) or infer(rust_name, types)
        types[rust_name] = kind
        references = re.findall(r"\b[A-Za-z_]\w*", expression)
        value = eval(re.sub(r"\b[A-Za-z_]\w*", lambda match: str(values[match[0]]), expression))
        values[name] = value
        low, high = RANGES[kind]
        if not low <= value < high:
            raise ValueError(f"{name} = {value} does not fit {kind}")
        same_types = all(types.get(reference.upper()) == kind for reference in references)
        rust_value = expression.replace("~", "!") if same_types else hex(value)
        lines.append(f"pub const {rust_name}: {kind} = {rust_value};")
    with open(TARGET, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


main()
